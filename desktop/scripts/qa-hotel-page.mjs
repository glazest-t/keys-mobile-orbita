import {createRequire} from 'node:module';
const require=createRequire(new URL('../../app/package.json',import.meta.url));
const {chromium,expect}=require('@playwright/test');
const browser=await chromium.launch({executablePath:process.env.DESKTOP_QA_BROWSER||chromium.executablePath(),args:['--enable-unsafe-swiftshader']});
const page=await browser.newPage({viewport:{width:1440,height:1000}}),errors=[];
page.on('pageerror',e=>errors.push(e.message));
await page.goto('http://127.0.0.1:5180/?catalogue=booking-hotel#booking-flow');
await page.waitForFunction(()=>document.documentElement.dataset.catalogueStatus==='ready');
await expect(page.locator('.desktop-hotel-rooms .room-offer').first()).toBeVisible();
await expect(page.locator('.desktop-flow[data-step="hotel"]>.desktop-flow-layout>.desktop-flow-footer')).toHaveCount(0);
await page.waitForTimeout(1200);
const photo=await page.locator('.source-hotel-hero').boundingBox(),summary=await page.locator('.desktop-hotel-summary').boundingBox();
if(summary.x<photo.x+photo.width)throw Error('Summary not to right of photo');
await page.screenshot({path:'../.desktop-work/qa/hotel-layout-top.png'});
await page.getByRole('button',{name:/Выбрать номер от/}).click();
await page.waitForTimeout(700);
await page.screenshot({path:'../.desktop-work/qa/hotel-layout-rooms.png'});
await expect(page.locator('.desktop-hotel-information .section-label').getByRole('button',{name:'Все',exact:true})).toHaveCount(0);
await expect(page.locator('.desktop-hotel-reviews .review-card').first()).toBeVisible();
await page.locator('#hotel-reviews').scrollIntoViewIfNeeded();
await page.waitForTimeout(700);
await page.screenshot({path:'../.desktop-work/qa/hotel-layout-reviews.png'});
await page.getByRole('button',{name:'Под ваши предпочтения — изменить'}).click();
await expect(page.getByRole('dialog')).toBeVisible();await page.getByRole('button',{name:'Закрыть',exact:true}).click();
await page.locator('.room-link').filter({hasText:'Оснащение номера'}).first().click();
await expect(page.getByRole('dialog')).toBeVisible();await page.getByRole('button',{name:'Понятно',exact:true}).click();
await page.locator('.room-rate-price button').first().click();
await expect(page.getByRole('heading',{name:'Оформление бронирования'})).toBeVisible();
await page.getByRole('button',{name:'Назад',exact:true}).click();
await expect(page.locator('.desktop-hotel-rooms')).toBeVisible();
await page.setViewportSize({width:1024,height:720});
await page.waitForTimeout(300);
if(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth))throw Error('Desktop overflow');
await page.screenshot({path:'../.desktop-work/qa/hotel-layout-1024.png'});
await page.goto('http://127.0.0.1:5173/?catalogue=booking-hotel#booking-flow');
await page.waitForFunction(()=>document.documentElement.dataset.catalogueStatus==='ready');
await expect(page.locator('.desktop-hotel-overview')).toHaveCount(0);
await expect(page.locator('.hotel-cta')).toBeVisible();
await expect(page.locator('.rooms-selection')).toHaveCount(0);
if(errors.length)throw Error(errors.join('\n'));
console.log('PASS desktop layout, full details, room selection to checkout and back, 1024px, mobile unchanged');
await browser.close();
