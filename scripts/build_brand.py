#!/usr/bin/env python3
"""Build the local brand package from the chosen source; never edit the archive.
Dependencies: lxml, fonttools, uharfbuzz (only for outlined SVG generation).
"""
import copy
import hashlib
import json
import shutil
from pathlib import Path
from urllib.parse import quote
from lxml import etree, html
from fontTools.ttLib import TTFont
from fontTools.pens.svgPathPen import SVGPathPen
from fontTools.pens.transformPen import TransformPen
import uharfbuzz as hb

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / 'проект в Клоде/project'
KIT = SOURCE / 'brand-kit'
OUT = ROOT / 'design'
DOC = ROOT / 'docs/brand'
SVG = '{http://www.w3.org/2000/svg}'


def write_json(path, value):
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(json.dumps(value, ensure_ascii=False, indent=2)+'\n')


def tokens():
    base = json.loads((KIT/'tokens/tokens.json').read_text())
    # The user's selected screens take precedence over earlier brand-kit defaults.
    base['radius']['button'] = 16
    base['type']['h1']['tracking'] = -0.8 / 26
    base['space']['headerPadding'] = 20
    base['glass']['fill'] = '#FFFFFFC4'
    base['size']['keyButton'] = 54
    base['motion']['duration'].update({'splash':2400,'tab':200,'press':120,'release':240,'switch':300,'toast':300,'onboardingOpacity':600,'onboardingTransform':800,'onboardingFinish':1400})
    base['motion']['ease']['iosPush']='cubic-bezier(.32,.72,0,1)'
    base['color']['gradient'].update({
        'search': 'radial-gradient(120% 100% at 20% 0%,#5B48FF 0%,#2F5BFF 70%)',
        'friendly': 'linear-gradient(155deg,#063F3C 0%,#0B6B63 55%,#13A08D 100%)',
        'rewards': 'linear-gradient(140deg,#2F5BFF,#5B48FF)',
        'loyaltySoft': 'linear-gradient(110deg,#FFFFFF,#EEF0FF 45%,#DCD8FF 80%,#CDEFFF)',
    })
    data = {'version':'1.1.0-working','visualAuthority':'Ключи - Все экраны.dc.html',
            'primitive':base, 'semantic':{
        'surface.app':'{color.neutral.pearl}', 'surface.card':'{color.neutral.white}',
        'text.primary':'{color.neutral.ink}', 'text.secondary':'{color.neutral.slate}',
        'text.disabled':'{color.neutral.muted}', 'text.onAccent':'{color.neutral.white}',
        'action.primary':'{color.brand.cobalt}', 'action.pressed':'{color.brand.cobaltPressed}',
        'action.tint':'{color.brand.cobaltTint}', 'border.subtle':'{color.neutral.line}',
        'status.success':'{color.status.success}', 'status.errorText':'#BE3040',
        'status.warningText':'#855609', 'focus.ring':'{color.neutral.slate}',
        'feature.friendly':'{color.gradient.friendly}', 'feature.rewards':'{color.gradient.rewards}',
        'feature.search':'{color.gradient.search}', 'feature.loyaltySoft':'{color.gradient.loyaltySoft}',
    }, 'component':{
        'header.markSize':'28px','header.padding':'20px','screen.padding':'16px',
        'button.height':'52px','button.radius':'16px','button.textSize':'15px',
        'key.height':'54px','card.radius':'22px','hero.radius':'28px',
        'rate.radius':'20px','nav.height':'64px','nav.radius':'32px','nav.inset':'14px',
        'nav.fill':'#FFFFFFC4','target.min':'44px','sheet.radius':'28px',
    }, 'accessibility':{'glassSolid':'#FFFFFFF5','reducedMotion':'no_rotation_no_parallax',
                        'minimumTarget':44,'smallTextMinimumContrast':4.5},
    'provenance':{
        'base':'проект в Клоде/project/brand-kit/tokens/tokens.json',
        'overrides':{'radius.button':'f1/s2: 16px', 'type.h1.tracking':'f1/v1: -0.8px',
                     'glass.fill':'f1/s2/v1: #ffffffc4', 'space.headerPadding':'f1: 20px',
                     'size.keyButton':'s2: 54px', 'motion.duration.splash':'D-011: github-onboarding 2400ms', 'focus.ring':'D-010: neutral focus', 'color.gradient':'f1/fr4/v1: extracted styles'},
        'newRoles':['status.errorText: darker text on light error background',
                    'status.warningText: darker text on light warning background']}}
    # Extract the exact search surface instead of approximating its stops.
    tree = html.fromstring((SOURCE/'Ключи - Все экраны.dc.html').read_text())
    for el in tree.get_element_by_id('f1').xpath('.//section[@style]'):
        style=el.get('style')
        if 'Знаете, куда едете' in ''.join(el.itertext()):
            base['color']['gradient']['search']=next(r.split(':',1)[1] for r in style.split(';') if r.startswith('background:'))
    write_json(OUT/'tokens.json',data)
    def resolve(value):
        if isinstance(value,str) and value.startswith('{'):
            obj=base
            for part in value[1:-1].split('.'): obj=obj[part]
            return obj
        return value
    css=['/* Generated by scripts/build_brand.py from design/tokens.json. */',
         '@font-face{font-family:Onest;src:url("fonts/Onest-Variable.ttf") format("truetype");font-weight:100 900;font-display:swap}',
         '@font-face{font-family:Unbounded;src:url("fonts/Unbounded-Variable.ttf") format("truetype");font-weight:200 900;font-display:swap}', ':root{']
    for group in ['semantic','component']:
        for key,value in data[group].items(): css.append(f'  --k-{key.replace(".","-")}:{resolve(value)};')
